/**
 * Lucento's bundled animations. All are original vector Lottie files generated by `tools/lottie` (see
 * docs/design/ANIMATION_ASSETS.md); none is downloaded at runtime. Illustrations have a night variant so
 * outlines and paper stay legible on the midnight theme.
 */
enum class LucentoAnimation(@RawRes val day: Int, @RawRes val night: Int, val loops: Boolean) {
    Welcome(R.raw.onboarding_welcome, R.raw.onboarding_welcome_night, loops = false),
    EmptyTransactions(R.raw.empty_transactions, R.raw.empty_transactions_night, loops = false),
    EmptyBudgets(R.raw.empty_budgets, R.raw.empty_budgets_night, loops = false),
    EmptyGoals(R.raw.empty_goals, R.raw.empty_goals_night, loops = false),
    EmptyRecurring(R.raw.empty_recurring, R.raw.empty_recurring_night, loops = false),
    ReceiptScanning(R.raw.receipt_scanning, R.raw.receipt_scanning_night, loops = true),
    Saved(R.raw.feedback_saved, R.raw.feedback_saved, loops = false),
    Milestone(R.raw.feedback_milestone, R.raw.feedback_milestone, loops = false),
    Loading(R.raw.loading_dots, R.raw.loading_dots, loops = true),
    Mascot(R.raw.lucento_mascot_sun, R.raw.lucento_mascot_moon, loops = false),
}

/**
 * Plays one of [LucentoAnimation] with consistent rules:
 *
 * - **Reduced motion** (system "Remove animations"): nothing moves. One-shot animations show their final,
 *   complete frame (a finished check, a whole illustration); loops show their first frame.
 * - **One-shot** animations play once and hold their last frame; [onFinished] fires once at the end (or
 *   immediately under reduced motion) so callers never wait on an animation that will not run.
 * - **Loops** run only while [playing] and while composed: leaving the screen disposes the clock.
 * - [iterations] limits a loop (e.g. a mascot idles a few cycles, then rests) — use [LottieConstants.IterateForever]
 *   only for genuine in-progress states.
 * - [marker] restricts playback to a named segment (the mascot's expressions).
 * - If the file cannot be parsed, [fallback] is shown instead, so the screen stays usable.
 *
 * Animations are decorative unless [contentDescription] is given. They never drive app logic.
 */
@Composable
fun LucentoLottieAnimation(
    animation: LucentoAnimation,
    modifier: Modifier = Modifier,
    playing: Boolean = true,
    iterations: Int = if (animation.loops) LottieConstants.IterateForever else 1,
    marker: String? = null,
    contentDescription: String? = null,
    contentScale: ContentScale = ContentScale.Fit,
    onFinished: (() -> Unit)? = null,
    fallback: @Composable () -> Unit = {},
) {
    val reducedMotion = LucentoTheme.reducedMotion
    val res = if (LucentoTheme.isDark) animation.night else animation.day
    val result = rememberLottieComposition(LottieCompositionSpec.RawRes(res))
    val composition by result
    val semantics = if (contentDescription != null) {
        Modifier.semantics { this.contentDescription = contentDescription }
    } else {
        Modifier.clearAndSetSemantics { }
    }
    val finished by rememberUpdatedState(onFinished)

    if (result.isFailure) {
        Box(modifier.then(semantics), contentAlignment = Alignment.Center) { fallback() }
        LaunchedEffect(Unit) { finished?.invoke() }
        return
    }

    val clipSpec = remember(marker) { marker?.let { LottieClipSpec.Marker(it) } }
    val state = animateLottieCompositionAsState(
        composition = composition,
        isPlaying = playing && !reducedMotion,
        restartOnPlay = false,
        clipSpec = clipSpec,
        iterations = iterations,
    )
    val oneShot = iterations != LottieConstants.IterateForever
    val staticProgress = remember(composition, marker, oneShot) {
        composition?.let { staticFrameProgress(it, marker, atEnd = oneShot) } ?: 0f
    }

    if (oneShot) {
        LaunchedEffect(composition, reducedMotion, state.isAtEnd) {
            if (composition != null && (reducedMotion || state.isAtEnd)) finished?.invoke()
        }
    }

    LottieAnimation(
        composition = composition,
        progress = { if (reducedMotion) staticProgress else state.progress },
        modifier = modifier.then(semantics),
        contentScale = contentScale,
    )
}

/** Progress (0..1) of the first or last frame of [marker] (or of the whole file) for a still image. */
private fun staticFrameProgress(composition: LottieComposition, marker: String?, atEnd: Boolean): Float {
    val start = composition.startFrame
    val length = (composition.endFrame - start).coerceAtLeast(1f)
    val m = marker?.let { composition.getMarker(it) }
    val frame = when {
        m == null -> if (atEnd) composition.endFrame - 1f else start
        atEnd -> m.getStartFrame() + m.getDurationFrames() - 1f
        else -> m.getStartFrame()
    }
    return ((frame - start) / length).coerceIn(0f, 1f)
}
