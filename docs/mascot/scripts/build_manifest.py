"""Rebuild MASCOT_ASSET_MANIFEST.json from files on disk + curated QA notes.
Run from docs/mascot: python scripts/build_manifest.py   (measured fields come from mascot_assets.inspect)"""
import sys, json
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
import mascot_assets as M
from build_v3 import SRC, LEVEL, V3

T = ["thriving", "steady", "getting_tight", "concerned", "over_plan"]
P = ["hero_neutral", "greeting_happy", "thinking", "pointing", "success", "caution", "sleeping"]
ISSUES = {
    ("over_plan", "thinking"): ["sleeve/hem fraying still heavier than over_plan hero_neutral (v3 regeneration improved scarf only partially); review for dignified tone"],
    ("over_plan", "greeting_happy"): ["scarf ends more frayed than over_plan hero_neutral; minor inconsistency"],
}
V3_NOTES = {
    "concerned": "v3 (user request): light scruffy stubble + teary eyes / single tear; sleeping shows tear track",
    "over_plan": "v3 (user request): fuller ragged beard + visible tears on cheeks; sleeping shows tear tracks",
}
COMMON = [
    "AI-regenerated from the user-created concept sheet; not an exact recovery of any original layer",
    "generator-native 1024x1024 JPEG on chroma green; keyed, edge-decontaminated, crystal-levelled, then 2x LANCZOS upscaled (premultiplied) to 2048 - resampled, not native 2048",
    "flattened single layer; crystal brightness edited in-pixel (scripts/build_v3.py, same pipeline as build_v2.py) and glow is a separate layer",
    "placement consistent from generator (feet baseline varies by up to ~60px for standing poses); sleeping poses sit lower by design",
]
build = {(e["tier"], e["pose"]): e for e in json.loads(Path("reports/build_v3_log.json").read_text())}
assets = []
for f, desc in [("assets/source/01M5MZKDTJ1NM8NA87K8DHBTQ7.png", "user-created concept sheet (original filename)"),
                ("assets/source/lucento_concept_sheet_reference.png", "copy of user-created concept sheet")]:
    i = M.inspect(f)
    assets.append(dict(id=Path(f).stem, filename=f, category="source_reference", tier=None, pose=None, dimensions=i["size"],
        color_mode=i["mode"], alpha_status="none", canvas=i["size"], pivot=None, source=desc,
        provenance="user-created: the user states they created this concept sheet themselves (their own original concept). Not legally cleared.",
        production_status="source", validation_status="inspected: RGB no alpha, checkerboard score 0.030 (not baked), has labels/background",
        limitations=["concept sheet with text and gradient background; reference only"]))
for t in T:
    for p in P:
        d = "wellness_tiers" if p == "hero_neutral" else "expressions"
        f = f"assets/{d}/lucento_{t}_{p}_v3.png"
        i = M.inspect(f); b = build[(t, p)]
        iss = ISSUES.get((t, p), [])
        ok = i["alpha_genuine"] and not i["edge_touch"] and not i["checkerboard_suspected"] and i["size"] == [2048, 2048]
        assets.append(dict(id=f"lucento_{t}_{p}_v3", filename=f, category="character_full", tier=t, pose=p,
            dimensions=i["size"], color_mode=i["mode"], alpha_status="genuine" if i["alpha_genuine"] else "invalid",
            alpha_stats=i["alpha"], canvas=[2048, 2048], content_bbox=i["content_bbox"], min_padding_px=i["min_padding_px"],
            pivot={"x": 1024, "y": 1024, "note": "canvas centre; standing feet baseline ~y=1650-1715"},
            source=b["source"], native_processed=f"assets/processed/{t}_{p}_v3_native1024.png",
            crystal_level=LEVEL[t], crystal_luma_before=b["crystal_luma_before"], crystal_luma_after=b["crystal_luma_after"],
            provenance="AI-generated 2026-10-23 (Grok Bot image tool) using the user-created concept sheet and earlier generations as reference; processed by scripts/build_v3.py" + (" [regenerated in round 3]" if (t, p) in V3 else " [raw unchanged since v2; reprocessed]"),
            production_status=("needs_cleanup" if (iss or not ok) else "prototype"),
            validation_status=("automated: pass" if ok else "automated: FAIL") + "; visual: light/dark previews + dark hair-edge zoom reviewed 2026-10-23" ,
            design_notes=V3_NOTES.get(t), limitations=iss + COMMON, supersedes=f"assets/backup_v2/{d}/lucento_{t}_{p}_v2.png"))
for t, lv in M.TIER_GLOW.items():
    f = f"assets/layers/torch_glow/torch_glow_{t}.png"; i = M.inspect(f)
    assets.append(dict(id=f"torch_glow_{t}", filename=f, category="layer_glow", tier=t, pose=None, dimensions=i["size"], color_mode=i["mode"],
        alpha_status="genuine (procedural radial)", canvas=i["size"], pivot={"x": 512, "y": 512}, source="procedural: mascot_assets.py glow",
        provenance="procedurally generated by original code", peak_alpha_fraction=lv, production_status="prototype",
        validation_status="automated pass; composite reviewed in assets/previews/torch_glow_levels_v2_preview.png (moved to assets/backup_v2/previews/; glow layers unchanged in v3)",
        limitations=["placement on 2048 standing-pose canvas: centre (1620,660), ~700px; sleeping poses: crystal ~ (1535,830)"]))
for n in ["body", "back_hair", "front_hair", "eyes_open", "eyes_closed", "eyebrows", "mouths", "clothing", "scarf", "satchel_strap",
          "arm_left", "arm_right", "torch_handle", "torch_crystal", "ambient_sparkles", "ground_shadow"]:
    assets.append(dict(id=f"layer_{n}", filename=None, category="layer", production_status="missing", validation_status="n/a",
        limitations=["flattened generator output only; separation requires manual illustration/rigging"]))
m = {"schema_version": 3, "generated": "2026-10-23", "root": "docs/mascot",
     "statuses": ["source", "prototype", "needs_cleanup", "approved", "missing"],
     "note": "No asset is 'approved': approval requires human art-direction sign-off after MASCOT_ASSET_QA.md. v1 masters in assets/backup_v1/, v2 masters/processed/previews in assets/backup_v2/ (moved, not deleted).",
     "assets": assets}
Path("MASCOT_ASSET_MANIFEST.json").write_text(json.dumps(m, indent=2) + "\n")
from collections import Counter
print(Counter(a["production_status"] for a in assets))
