"""
Builds a one-paste SQL file for the Supabase SQL editor from migration files, in order, inside one transaction, with a
read-only verification query at the end. The editor doesn't record migrations, so this is how the owner applies them.

    python tools/supabase/build_apply.py docs/monetization/PRODUCTION_APPLY.sql \
        20261105120000_lucento_shared.sql 20261105120100_lucento_shared_privileges.sql ...

Never edit the output by hand: change the migration and regenerate.
"""
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MIGRATIONS = os.path.join(HERE, "..", "..", "supabase", "migrations")

VERIFY = """
-- ======================================================================================= verify (read-only)
-- Run after the commit. Every row should say ok.
select check_name, case when passed then 'ok' else 'MISSING' end as result from (values
  ('Lucento Shared tables', to_regclass('public.shared_spaces') is not null and to_regclass('public.space_members') is not null and to_regclass('public.space_invites') is not null),
  ('Shared: transactions.created_by', exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'transactions' and column_name = 'created_by')),
  ('Multicurrency: ledger_settings', to_regclass('public.ledger_settings') is not null),
  ('Multicurrency: transactions.base_amount_minor', exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'transactions' and column_name = 'base_amount_minor')),
  ('Entitlements tables', to_regclass('public.entitlements') is not null and to_regclass('public.purchase_links') is not null and to_regclass('lucento_private.plan_limits') is not null),
  ('consume_ai_request for signed-in only', to_regprocedure('public.consume_ai_request()') is not null and has_function_privilege('authenticated', 'public.consume_ai_request()', 'execute') and not has_function_privilege('anon', 'public.consume_ai_request()', 'execute')),
  ('apply_play_purchase for the service role only', exists (select 1 from pg_proc where proname = 'apply_play_purchase' and has_function_privilege('service_role', oid, 'execute') and not has_function_privilege('authenticated', oid, 'execute') and not has_function_privilege('anon', oid, 'execute'))),
  ('delete_my_account (applied earlier)', to_regprocedure('public.delete_my_account()') is not null),
  ('RLS on every new table', not exists (select 1 from pg_class c join pg_namespace n on n.oid = c.relnamespace where c.relkind = 'r' and not c.relrowsecurity and (n.nspname, c.relname) in (('public','shared_spaces'),('public','space_members'),('public','space_invites'),('public','ledger_settings'),('public','entitlements'),('public','purchase_links'),('lucento_private','plan_limits'))))
) as checks(check_name, passed);
"""


def main(out_path, names):
    parts = [
        "-- One paste for the Supabase SQL editor. Generated by tools/supabase/build_apply.py from these migrations, in",
        "-- this order; don't edit by hand. If any statement fails, the whole transaction rolls back and nothing changes.",
        "-- The dashboard may warn about `drop ... if exists` guards and RLS: both are expected (choose Run and enable RLS).",
    ]
    parts += ["--   " + n for n in names]
    parts += ["", "begin;", ""]
    for name in names:
        sql = io.open(os.path.join(MIGRATIONS, name), encoding="utf-8").read().rstrip() + "\n"
        parts += ["-- " + "=" * 100, "-- " + name, "-- " + "=" * 100, sql]
    parts += ["commit;", VERIFY]
    io.open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(parts))
    print("wrote %s from %d migrations" % (out_path, len(names)))


if __name__ == "__main__":
    if len(sys.argv) < 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2:])
