"""
Builds docs/mission-control/APPLY_MARKETING.sql: Mission Control's Marketing approvals migration as one paste for the
Supabase SQL editor (lucento-mission-control DEPLOYMENT.md part I, step 1), in APPLY_MISSION_CONTROL.sql's format: a
5-line header, two blank lines, then each migration under a banner of 101 '=' with its file name.

    python tools/supabase/build_marketing_apply.py            # (re)writes the file
    python tools/supabase/build_marketing_apply.py --check    # exit 1 if it is out of date

--check also rebuilds APPLY_MISSION_CONTROL.sql from its four migrations with the same code and compares it byte for
byte, so the two pastes keep one format. Checked by tools/sql-verify/catch_up_check.mjs (part D). Never edit the output
by hand: change the migration and regenerate.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
MIGRATIONS = ROOT / 'supabase' / 'migrations'
DOCS = ROOT / 'docs' / 'mission-control'
BANNER = '-- ' + '=' * 101

MARKETING = ['20261117090000_mission_control_marketing.sql']
MARKETING_HEADER = [
    '-- Mission Control, Marketing approvals: one paste for the Supabase SQL editor (DEPLOYMENT.md part I, step 1).',
    '-- Generated by tools/supabase/build_marketing_apply.py from the migration below; do not edit here, edit that.',
    '-- Paste it after APPLY_MISSION_CONTROL.sql (and again whenever that is pasted again), then run VERIFY_MARKETING.sql.',
    '-- Safe to run twice: every statement is create-if-missing or create-or-replace. Apply to lucento-test first.',
    '-- Beyond its new objects it changes the ingest-secret purposes, the job_runs job list and mc_api.nav_badges.',
]
MISSION_CONTROL = [
    '20261116090000_mission_control_core.sql',
    '20261116090100_mission_control_tables.sql',
    '20261116090200_mission_control_functions.sql',
    '20261116090300_mission_control_api.sql',
]


def read(path):
    return path.read_bytes().decode('utf-8')


def build(header, names):
    if len(header) != 5:
        raise SystemExit('the header is 5 lines')
    sections = []
    for name in names:
        body = read(MIGRATIONS / name)
        if '\r' in body:
            raise SystemExit('%s has CRLF line endings: convert it to LF first' % name)
        sections.append('%s\n-- %s\n%s\n\n%s' % (BANNER, name, BANNER, body))
    return '\n'.join(header) + '\n\n\n' + '\n'.join(sections)


def main():
    out = DOCS / 'APPLY_MARKETING.sql'
    text = build(MARKETING_HEADER, MARKETING)
    if '--check' in sys.argv[1:]:
        ok = True
        if not out.exists() or read(out) != text:
            print('%s is out of date: run python tools/supabase/build_marketing_apply.py' % out.relative_to(ROOT))
            ok = False
        mission_control = read(DOCS / 'APPLY_MISSION_CONTROL.sql')
        if build(mission_control.split('\n')[:5], MISSION_CONTROL) != mission_control:
            print('APPLY_MISSION_CONTROL.sql no longer matches this format (or its migrations changed)')
            ok = False
        if ok:
            print('APPLY_MARKETING.sql is up to date; APPLY_MISSION_CONTROL.sql has the same format')
        sys.exit(0 if ok else 1)
    out.write_bytes(text.encode('utf-8'))
    print('wrote %s (%d characters) from %s' % (out.relative_to(ROOT), len(text), ', '.join(MARKETING)))


if __name__ == '__main__':
    main()
